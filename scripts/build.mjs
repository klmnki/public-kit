import './build-examples.mjs';
import {mkdir,cp,copyFile,readFile,writeFile,rm} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {readWorldBankPage} from '../lib/observations.mjs';
await mkdir('dist',{recursive:true});
await rm('dist/model.mjs',{force:true});
await cp('site','dist',{recursive:true});
await copyFile('data/catalogue.json','dist/catalogue.json');
await copyFile('data/repeatable-examples.json','dist/repeatable-examples.json');
await cp('examples','dist/examples',{recursive:true,filter:path=>!path.replaceAll('\\','/').split('/').includes('.cache')});
await copyFile('lib/observations.mjs','dist/observations.mjs');
await copyFile('data/verified-example.json','dist/verified-example.json');
await copyFile('SKILL.md','dist/SKILL.md');
await copyFile('LICENSE','dist/LICENSE');
await copyFile('NOTICE.md','dist/NOTICE.md');
const example=JSON.parse(await readFile('data/verified-example.json','utf8'));
const csvValue=v=>'"'+String(v??'').replaceAll('"','""')+'"';
const csv=[['country','iso3','year','population','unit','footnote','source_url','retrieved_at'],...readWorldBankPage(example.response).map(r=>[r.name,r.country,r.year,r.value,example.unit,r.footnote,example.sourceUrl,example.retrievedAt])].map(row=>row.map(csvValue).join(',')).join('\r\n');
await writeFile('dist/public-kit-population-2020-2024.csv',csv);
const sum=createHash('sha256').update(await readFile('SKILL.md')).digest('hex');
await writeFile('dist/SHA256SUMS.txt',sum+'  SKILL.md\n');
console.log('Built Public Kit site and identical standalone SKILL.md.');
